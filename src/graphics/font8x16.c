void draw_char_8x16(int x, int y, char c, uint8_t color) {
    if (c < 32 || c > 127) c = 32;
    
    const uint8_t* char_data = font_8x16[c - 32];
    
    for (int row = 0; row < 16; row++) {
        uint8_t row_data = char_data[row];
        for (int col = 0; col < 8; col++) {
            if (row_data & (0x80 >> col)) {
                vga_set_pixel(x + col, y + row, color);
            }
        }
    }
}

void draw_string_8x16(int x, int y, const char* str, uint8_t color) {
    int orig_x = x;
    while (*str) {
        if (*str == '\n') {
            y += 16;
            x = orig_x;
        } else {
            draw_char_8x16(x, y, *str, color);
            x += 8;
        }
        str++;
    }
}
